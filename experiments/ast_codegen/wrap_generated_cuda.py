# ResNet-18 224x224 (M10b).  External tensors and post-fusion intermediates
# are generated from the block table to keep the ~110 entries consistent.
# Fusion (conv+BN+ReLU, conv+BN+Add) means convX_out/bnX_out buffers are
# never materialised on device; the live cross-kernel buffers are the stem
# relu1_out/pool_out and, per block, relu1_out + add_out (ReLU after the
# residual add is in place on add_out) plus shortcut_out for the three
# projection blocks.
RESNET18_BLOCKS = [
    ("l1_b1", 64,  64,  56, False),
    ("l1_b2", 64,  64,  56, False),
    ("l2_b1", 64,  128, 28, True),
    ("l2_b2", 128, 128, 28, False),
    ("l3_b1", 128, 256, 14, True),
    ("l3_b2", 256, 256, 14, False),
    ("l4_b1", 256, 512, 7,  True),
    ("l4_b2", 512, 512, 7,  False),
]


def _resnet18_specs():
    spec = [
        ("input",   [1, 3, 224, 224], "float"),
        ("conv1_w", [64, 3, 7, 7],    "float"),
        ("conv1_b", [64],             "float"),
        ("bn1_mean",  [64], "float"),
        ("bn1_var",   [64], "float"),
        ("bn1_gamma", [64], "float"),
        ("bn1_beta",  [64], "float"),
    ]
    for prefix, inch, outch, m, proj in RESNET18_BLOCKS:
        spec.append((f"{prefix}_w1", [outch, inch, 3, 3], "float"))
        spec.append((f"{prefix}_b1", [outch], "float"))
        spec.append((f"{prefix}_w2", [outch, outch, 3, 3], "float"))
        spec.append((f"{prefix}_b2", [outch], "float"))
        for bn in ("bn1", "bn2"):
            for s in ("mean", "var", "gamma", "beta"):
                spec.append((f"{prefix}_{bn}_{s}", [outch], "float"))
        if proj:
            spec.append((f"{prefix}_shortcut_w", [outch, inch, 1, 1], "float"))
            spec.append((f"{prefix}_shortcut_b", [outch], "float"))
            for s in ("mean", "var", "gamma", "beta"):
                spec.append((f"{prefix}_shortcut_{s}", [outch], "float"))
    spec.append(("fc_w", [1000, 512], "float"))
    spec.append(("fc_b", [1000], "float"))
    spec.append(("output", [1, 1000], "float"))
    return spec


