"""Wrap a generated CUDA body into a compilable .cu test program.

Usage:
    python3 wrap_generated_cuda.py <network> <body.cu> <output.cu>

The wrapper declares __constant__ symbols for tensors and scalars, allocates
explicit device memory with cudaMalloc, copies data with cudaMemcpy, runs the
generated host function, and writes the binary output file.  This replaces the
previous __managed__ unified-memory model with explicit host/device transfers.

Intermediate tensors declared in INTERMEDIATES can share device buffers via
REUSE_GROUPS, reducing the number of cudaMalloc/cudaFree calls for chain
networks.
"""

