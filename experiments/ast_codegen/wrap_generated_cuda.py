# Intermediate tensor reuse groups.  Each group lists intermediates that can
# safely share one device buffer because they have the same element count and
# are only connected by element-wise / layout-equivalent producer-consumer
# relationships.  External inputs/outputs must NOT appear here.
REUSE_GROUPS = {}


def shape_to_brackets(shape):
    return "".join(f"[{d}]" for d in shape)


def tensor_nelements(shape):
    n = 1
    for d in shape:
        n *= d
    return n


def constant_ptr_decl(name, shape, dtype):
    """Return a __constant__ declaration whose type matches how kernels index it.

    - 1D [N]           -> __constant__ float* name;
    - 2D [M, N]        -> __constant__ float (*name)[N];
    - 3D [M, N, P]     -> __constant__ float (*name)[N][P];
    - 4D [B, C, H, W]  -> __constant__ float (*name)[C][H][W];
    """
    if len(shape) == 1:
        return f"__constant__ {dtype}* {name};"
    rest = shape_to_brackets(shape[1:])
    return f"__constant__ {dtype} (*{name}){rest};"


def compute_reuse_groups(network):
    """Validate REUSE_GROUPS and return (groups, grouped_vars).

    groups is a list of dicts: {'members': [...], 'bytes': N}.
    grouped_vars is the set of all variables appearing in any group.
    """
    intermediates = {name: shape for name, shape, _ in INTERMEDIATES.get(network, [])}
    raw_groups = REUSE_GROUPS.get(network, [])
    groups = []
    grouped_vars = set()

    for members in raw_groups:
        if not members:
            continue
        # All members must be intermediates.
        for m in members:
            if m not in intermediates:
                raise ValueError(
                    f"Reuse group for {network} contains non-intermediate '{m}'"
                )
        # Each variable can only belong to one group.
        for m in members:
            if m in grouped_vars:
                raise ValueError(
                    f"Intermediate '{m}' appears in more than one reuse group for {network}"
                )
            grouped_vars.add(m)
        # All members must have the same element count.
        sizes = {tensor_nelements(intermediates[m]) for m in members}
        if len(sizes) != 1:
            raise ValueError(
                f"Reuse group for {network} has mismatched sizes: "
                f"{ {m: tensor_nelements(intermediates[m]) for m in members} }"
            )
        groups.append({"members": members, "bytes": list(sizes)[0] * 4})

    return groups, grouped_vars


def main():
    if len(sys.argv) != 4:
        print("Usage: wrap_generated_cuda.py <network> <body.cu> <output.cu>")
        sys.exit(1)

    network = sys.argv[1]
    body_path = Path(sys.argv[2])
    out_path = Path(sys.argv[3])

    if network not in TENSOR_SPECS:
        print(f"Unknown network: {network}")
        print(f"Supported: {list(TENSOR_SPECS.keys())}")
        sys.exit(1)

    body = body_path.read_text()

    spec = TENSOR_SPECS[network]
    input_specs = spec[:-1]
    output_spec = spec[-1]
    output_var, output_shape, _ = output_spec
    output_nelements = tensor_nelements(output_shape)
    output_bytes = output_nelements * 4  # float32

    all_tensors = spec + INTERMEDIATES.get(network, [])
    reuse_groups, grouped_vars = compute_reuse_groups(network)

    # __constant__ declarations for tensors and scalars.
    constant_decls = []
    for var_name, shape, dtype in all_tensors:
        constant_decls.append(constant_ptr_decl(var_name, shape, dtype))
    for var_name, dtype in SCALARS.get(network, []):
        constant_decls.append(f"__constant__ {dtype} {var_name};")

    # Device allocation and symbol binding.
    alloc_lines = []
    # First allocate shared buffers for reuse groups.
    for gidx, group in enumerate(reuse_groups):
        gid = f"g{gidx}"
        bytes_ = group["bytes"]
        alloc_lines.append(f"  size_t d_{gid}_bytes = {bytes_};")
        alloc_lines.append(f"  float* d_{gid} = NULL;")
        alloc_lines.append(
            f"  CUDA_CHECK(cudaMalloc((void**)&d_{gid}, d_{gid}_bytes));"
        )
        for var_name in group["members"]:
            alloc_lines.append(
                f"  CUDA_CHECK(cudaMemcpyToSymbol({var_name}, &d_{gid}, sizeof(d_{gid})));"
            )
        alloc_lines.append("")

    # Then allocate individual buffers for tensors not in a reuse group.
    for var_name, shape, dtype in all_tensors:
        if var_name in grouped_vars:
            continue
        n = tensor_nelements(shape)
        bytes_ = n * 4
        alloc_lines.append(f"  size_t {var_name}_bytes = {bytes_};")
        alloc_lines.append(f"  {dtype}* d_{var_name} = NULL;")
        alloc_lines.append(
            f"  CUDA_CHECK(cudaMalloc((void**)&d_{var_name}, {var_name}_bytes));"
        )
        alloc_lines.append(
            f"  CUDA_CHECK(cudaMemcpyToSymbol({var_name}, &d_{var_name}, sizeof(d_{var_name})));"
        )

    # Read inputs from binary into host staging buffers, then H2D.
    input_read_lines = []
    for var_name, shape, dtype in input_specs:
        n = tensor_nelements(shape)
        bytes_ = n * 4
        input_read_lines.append(f"  {dtype}* h_{var_name} = ({dtype}*)malloc({bytes_});")
        input_read_lines.append(f"  if (!h_{var_name}) {{ fprintf(stderr, \"malloc failed for {var_name}\\n\"); return 1; }}")
        input_read_lines.append(
            f"  {{ FILE* f = fopen(\"{network}_{var_name}.bin\", \"rb\");"
        )
        input_read_lines.append(
            f"    if (!f) {{ fprintf(stderr, \"Cannot open {network}_{var_name}.bin\\n\"); return 1; }}"
        )
        input_read_lines.append(
            f"    size_t nread = fread(h_{var_name}, sizeof({dtype}), {n}, f);"
        )
        input_read_lines.append(
            f"    fclose(f);"
        )
        input_read_lines.append(
            f"    if (nread != {n}) {{ fprintf(stderr, \"Failed to read {network}_{var_name}.bin\\n\"); return 1; }}"
        )
        input_read_lines.append("  }")
        input_read_lines.append(
            f"  CUDA_CHECK(cudaMemcpy(d_{var_name}, h_{var_name}, {bytes_}, cudaMemcpyHostToDevice));"
        )

    # Read scalars from binary and copy to __constant__ symbols.
    scalar_read_lines = []
    for var_name, dtype in SCALARS.get(network, []):
        scalar_read_lines.append(f"  {dtype} h_{var_name};")
        scalar_read_lines.append(
            f"  {{ FILE* f = fopen(\"{network}_{var_name}.bin\", \"rb\");"
        )
        scalar_read_lines.append(
            f"    if (!f) {{ fprintf(stderr, \"Cannot open {network}_{var_name}.bin\\n\"); return 1; }}"
        )
        scalar_read_lines.append(
            f"    fread(&h_{var_name}, sizeof({dtype}), 1, f);"
        )
        scalar_read_lines.append("    fclose(f);")
        scalar_read_lines.append("  }")
        scalar_read_lines.append(
            f"  CUDA_CHECK(cudaMemcpyToSymbol({var_name}, &h_{var_name}, sizeof(h_{var_name})));"
        )

    # Output host buffer and D2H copy after launch.
    output_host_lines = [
        f"  float* h_{output_var} = (float*)malloc({output_bytes});",
        f"  if (!h_{output_var}) {{ fprintf(stderr, \"malloc failed for {output_var}\\n\"); return 1; }}",
    ]

    # Cleanup code.
    cleanup_lines = []
    # Free shared group buffers.
    for gidx, _ in enumerate(reuse_groups):
        gid = f"g{gidx}"
        cleanup_lines.append(f"  CUDA_CHECK(cudaFree(d_{gid}));")
    # Free individual tensor buffers.
    for var_name, shape, dtype in all_tensors:
        if var_name in grouped_vars:
            continue
        cleanup_lines.append(f"  CUDA_CHECK(cudaFree(d_{var_name}));")
    # Free host staging buffers.
    for var_name, shape, dtype in input_specs:
        cleanup_lines.append(f"  free(h_{var_name});")
    cleanup_lines.append(f"  free(h_{output_var});")

    lines = [
        "#include <cuda_runtime.h>",
        "#include <math.h>",
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "",
        "#define CUDA_CHECK(call) \\",
        "  do { \\",
        "    cudaError_t err = (call); \\",
        "    if (err != cudaSuccess) { \\",
        "      fprintf(stderr, \"CUDA error at %s:%d: %s\\n\", __FILE__, __LINE__, cudaGetErrorString(err)); \\",
        "      exit(1); \\",
        "    } \\",
        "  } while (0)",
        "",
    ]
    lines.extend(constant_decls)
    lines.extend(["", body, ""])
    lines.append("int main(int argc, char** argv)")
    lines.append("{")
    lines.extend(alloc_lines)
    lines.append("")
    # Stage + H2D timing (covers input file reads and host-to-device copies).
    lines.append("  cudaEvent_t __io_start, __io_stop;")
    lines.append("  CUDA_CHECK(cudaEventCreate(&__io_start));")
    lines.append("  CUDA_CHECK(cudaEventCreate(&__io_stop));")
    lines.append("  CUDA_CHECK(cudaEventRecord(__io_start));")
    lines.extend(input_read_lines)
    lines.extend(scalar_read_lines)
    lines.append("  CUDA_CHECK(cudaEventRecord(__io_stop));")
    lines.append("  CUDA_CHECK(cudaEventSynchronize(__io_stop));")
    lines.append("  {")
    lines.append("    float __io_ms = 0.0f;")
    lines.append("    CUDA_CHECK(cudaEventElapsedTime(&__io_ms, __io_start, __io_stop));")
    lines.append(f'    printf("MEMTIME_H2D {network} %.6f\\n", __io_ms);')
    lines.append("  }")
    lines.append("")
    lines.extend(output_host_lines)
    lines.append("")
    lines.append("  cudaEvent_t __timer_start, __timer_stop;")
    lines.append("  CUDA_CHECK(cudaEventCreate(&__timer_start));")
    lines.append("  CUDA_CHECK(cudaEventCreate(&__timer_stop));")
    # Warmup + repeated timing (min/median over 20 inner iterations after 5
    # warmups), matching the PyTorch baseline regime (warmup 20, min/median
    # of 50).  The kernels are idempotent, so repeated calls are safe.
    lines.append(f"  for (int __w = 0; __w < 5; __w++) {network}();")
    lines.append("  CUDA_CHECK(cudaDeviceSynchronize());")
    lines.append("  float __best_ms = 1e30f;")
    lines.append("  float __all_ms[20];")
    lines.append("  for (int __it = 0; __it < 20; __it++) {")
    lines.append("    CUDA_CHECK(cudaEventRecord(__timer_start));")
    lines.append(f"    {network}();")
    lines.append("    CUDA_CHECK(cudaEventRecord(__timer_stop));")
    lines.append("    CUDA_CHECK(cudaEventSynchronize(__timer_stop));")
    lines.append("    float __elapsed_ms = 0.0f;")
    lines.append("    CUDA_CHECK(cudaEventElapsedTime(&__elapsed_ms, __timer_start, __timer_stop));")
    lines.append("    __all_ms[__it] = __elapsed_ms;")
    lines.append("    if (__elapsed_ms < __best_ms) __best_ms = __elapsed_ms;")
    lines.append("  }")
    lines.append("  for (int __i = 0; __i < 20; __i++)")
    lines.append("    for (int __j = __i + 1; __j < 20; __j++)")
    lines.append("      if (__all_ms[__j] < __all_ms[__i]) { float __t = __all_ms[__i]; __all_ms[__i] = __all_ms[__j]; __all_ms[__j] = __t; }")
    lines.append(f'    printf("TIME {network} %.6f\\n", __best_ms);')
    lines.append(f'    printf("TIMEMED {network} %.6f\\n", __all_ms[10]);')
    lines.append("  CUDA_CHECK(cudaEventDestroy(__timer_start));")
    lines.append("  CUDA_CHECK(cudaEventDestroy(__timer_stop));")
    lines.append("")
    # CUDA Graph replay timing, when the body provides a stream-taking
    # <network>_s(cudaStream_t) entry point (round-2 ResNet-18 work).
    # Captures the cooperative stage chain first; cooperative launches are
    # not capturable on all driver versions, so on capture failure we fall
    # back to the sequential chain <network>_seq_s.
    if f"void {network}_s(" in body and f"{network}_seq_s(" in body:
        lines.append("  {")
        lines.append("    cudaStream_t __gs;")
        lines.append("    cudaGraph_t __graph = NULL;")
        lines.append("    cudaGraphExec_t __gexec = NULL;")
        lines.append("    CUDA_CHECK(cudaStreamCreate(&__gs));")
        lines.append("    cudaError_t __ce = cudaStreamBeginCapture(__gs, cudaStreamCaptureModeThreadLocal);")
        lines.append(f"    if (__ce == cudaSuccess) {{ {network}_s(__gs); __ce = cudaStreamEndCapture(__gs, &__graph); }}")
        lines.append("    if (__ce != cudaSuccess) {")
        lines.append("      cudaGetLastError();  /* clear poisoned capture state */")
        lines.append("      __graph = NULL;")
        lines.append("      __ce = cudaStreamBeginCapture(__gs, cudaStreamCaptureModeThreadLocal);")
        lines.append(f"      if (__ce == cudaSuccess) {{ {network}_seq_s(__gs); __ce = cudaStreamEndCapture(__gs, &__graph); }}")
        lines.append("    }")
        lines.append("    if (__ce == cudaSuccess && __graph)")
        lines.append("      __ce = cudaGraphInstantiate(&__gexec, __graph, NULL, NULL, 0);")
        lines.append("    if (__ce == cudaSuccess && __gexec) {")
        lines.append("      for (int __w = 0; __w < 3; __w++) CUDA_CHECK(cudaGraphLaunch(__gexec, __gs));")
        lines.append("      CUDA_CHECK(cudaStreamSynchronize(__gs));")
        lines.append("      cudaEvent_t __ga, __gb;")
        lines.append("      CUDA_CHECK(cudaEventCreate(&__ga));")
        lines.append("      CUDA_CHECK(cudaEventCreate(&__gb));")
        lines.append("      float __gbest = 1e30f;")
        lines.append("      float __gall[20];")
        lines.append("      for (int __it = 0; __it < 20; __it++) {")
        lines.append("        CUDA_CHECK(cudaEventRecord(__ga, __gs));")
        lines.append("        CUDA_CHECK(cudaGraphLaunch(__gexec, __gs));")
        lines.append("        CUDA_CHECK(cudaEventRecord(__gb, __gs));")
        lines.append("        CUDA_CHECK(cudaEventSynchronize(__gb));")
        lines.append("        float __gms = 0.0f;")
        lines.append("        CUDA_CHECK(cudaEventElapsedTime(&__gms, __ga, __gb));")
        lines.append("        __gall[__it] = __gms;")
        lines.append("        if (__gms < __gbest) __gbest = __gms;")
        lines.append("      }")
        lines.append("      for (int __i = 0; __i < 20; __i++)")
        lines.append("        for (int __j = __i + 1; __j < 20; __j++)")
        lines.append("          if (__gall[__j] < __gall[__i]) { float __t = __gall[__i]; __gall[__i] = __gall[__j]; __gall[__j] = __t; }")
        lines.append(f'      printf("TIME_GRAPH {network} %.6f\\n", __gbest);')
        lines.append(f'      printf("TIMEGRAPH_MED {network} %.6f\\n", __gall[10]);')
        lines.append("      CUDA_CHECK(cudaEventDestroy(__ga));")
        lines.append("      CUDA_CHECK(cudaEventDestroy(__gb));")
        lines.append("    } else {")
        lines.append(f'      printf("TIME_GRAPH {network} unsupported\\n");')
        lines.append("    }")
        lines.append("  }")
        lines.append("")
    # If the generated body carries an instrumented <network>_kt() variant
    # (per-kernel CUDA-event timing), run it once here — after the TIME
    # measurement, so the extra events stay off the timed path.
    if f"void {network}_kt()" in body:
        lines.append(f"  {network}_kt();")
        lines.append("")
    lines.append(
        f"  CUDA_CHECK(cudaEventRecord(__io_start));"
    )
    lines.append(
        f"  CUDA_CHECK(cudaMemcpy(h_{output_var}, d_{output_var}, {output_bytes}, cudaMemcpyDeviceToHost));"
    )
    lines.append("  CUDA_CHECK(cudaEventRecord(__io_stop));")
    lines.append("  CUDA_CHECK(cudaEventSynchronize(__io_stop));")
    lines.append("  {")
    lines.append("    float __d2h_ms = 0.0f;")
    lines.append("    CUDA_CHECK(cudaEventElapsedTime(&__d2h_ms, __io_start, __io_stop));")
    lines.append(f'    printf("MEMTIME_D2H {network} %.6f\\n", __d2h_ms);')
    lines.append("  }")
    lines.append("  CUDA_CHECK(cudaEventDestroy(__io_start));")
    lines.append("  CUDA_CHECK(cudaEventDestroy(__io_stop));")
    lines.append("")
    lines.append(f"  FILE* fout = fopen(\"{network}_output.bin\", \"wb\");")
    lines.append("  if (!fout) { fprintf(stderr, \"Cannot open %s\\n\", \"" + network + "_output.bin\"); return 1; }")
    lines.append(f"  fwrite(h_{output_var}, sizeof(float), {output_nelements}, fout);")
    lines.append("  fclose(fout);")
    lines.append("")
    lines.extend(cleanup_lines)
    lines.append("  return 0;")
    lines.append("}")
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"Wrapped CUDA test written to {out_path}")


if __name__ == "__main__":
    main()
