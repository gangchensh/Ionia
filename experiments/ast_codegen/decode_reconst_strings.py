#!/usr/bin/env python3
"""Decode Coq-string literals inside REconst nodes of a symbolic Ionia AST.

transform_to_symbolic.py already handles the REconst "0"/"1" literals
generated by vrd; networks with arbitrary numeric constants (e.g. the
MiniTransformer GELU/LayerNorm constants) extract them as Coq
String/Ascii constructor lists (with extra parens from Pair unfolding),
which the streaming printer (which expects a native OCaml string in
REconst) cannot print.  This pass decodes every remaining REconst string
argument to a native OCaml string literal.

Usage: decode_reconst_strings.py in_sym.ml out_sym.ml
"""

import re
import sys

ASCII_RE = re.compile(
    r'Ascii\s*\(\s*(True|False)\s*,\s*(True|False)\s*,\s*(True|False)\s*,'
    r'\s*(True|False)\s*,\s*(True|False)\s*,\s*(True|False)\s*,'
    r'\s*(True|False)\s*,\s*(True|False)\s*\)')


def balanced_group_end(src, pos):
    """pos points at '('.  Return the index just past the matching ')'."""
    depth = 0
    i = pos
    while i < len(src):
        if src[i] == '(':
            depth += 1
        elif src[i] == ')':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return None


def parse_coq_string_at(src, pos):
    """Parse a Coq string literal starting at pos ('String' or 'EmptyString').

    The literal is 'String' followed by one balanced parenthesised group
    holding (Ascii ..., rest).  Returns (decoded_str, end_pos) or None.
    """
    if src.startswith('EmptyString', pos):
        return '', pos + len('EmptyString')
    if not src.startswith('String', pos):
        return None
    j = pos + len('String')
    while j < len(src) and src[j].isspace():
        j += 1
    if j >= len(src) or src[j] != '(':
        return None
    end = balanced_group_end(src, j)
    if end is None:
        return None
    inner = src[j + 1:end - 1]
    if 'EmptyString' not in inner:
        return None
    chars = []
    for m in ASCII_RE.finditer(inner):
        bits = [1 if b == 'True' else 0 for b in m.groups()]
        chars.append(chr(sum(b << i for i, b in enumerate(bits))))
    return ''.join(chars), end


def ocaml_string_literal(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def decode_reconst_strings(src):
    out = []
    idx = 0
    n_decoded = 0
    n_stubbed = 0
    for m in re.finditer(r'\bREconst\s*\(', src):
        # Opening paren of the argument pair.
        p = m.end() - 1
        # Scan to the comma at depth 1 separating the R value from the string.
        depth = 0
        q = p
        comma = -1
        while q < len(src):
            c = src[q]
            if c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
                if depth == 0:
                    break
            elif c == ',' and depth == 1:
                comma = q
                break
            q += 1
        if comma < 0:
            continue
        # Stub the R component: constructing any non-trivial real (Rplus/
        # Rdiv/IZR of n > 1, ...) at AST-build time reaches the un-realisable
        # classical axioms (sig_forall_dec via lowerCutAbove).  The streaming
        # printer only uses the string component, and nothing else consumes
        # the R component of an REconst (REscal/writeR is unused), so the
        # extracted value can safely be replaced by R0.  The Coq-side
        # semantics keeps the exact real value; only the extracted OCaml
        # drops it.
        rarg = src[p + 1:comma].strip()
        if rarg not in ('RbaseSymbolsImpl.coq_R0', 'RbaseSymbolsImpl.coq_R1'):
            out.append(src[idx:p + 1])
            out.append(' RbaseSymbolsImpl.coq_R0,')
            idx = comma + 1
            n_stubbed += 1
        # Skip whitespace and opening parens before the string literal.
        r = comma + 1
        while r < len(src) and (src[r].isspace() or src[r] == '('):
            r += 1
        # Already decoded (native OCaml string)?
        if r < len(src) and src[r] == '"':
            continue
        parsed = parse_coq_string_at(src, r)
        if parsed is None:
            continue
        decoded, end = parsed
        out.append(src[idx:r])
        out.append(ocaml_string_literal(decoded))
        idx = end
        n_decoded += 1
    out.append(src[idx:])
    return ''.join(out), n_decoded, n_stubbed


def main():
    infile, outfile = sys.argv[1], sys.argv[2]
    with open(infile, 'r') as f:
        src = f.read()
    src, n, n_stub = decode_reconst_strings(src)
    with open(outfile, 'w') as f:
        f.write(src)
    print(f"Decoded {n} REconst string literals, "
          f"stubbed {n_stub} REconst real components -> {outfile}")


if __name__ == '__main__':
    main()
